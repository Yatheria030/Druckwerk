export const PROFILES: FilamentProfile[] = RAW.map(([id, name, type, vendor, nozzle_min, nozzle_max, bed]) => ({ id, name, type, vendor, nozzle_min, nozzle_max, bed }));
const byId = new Map(PROFILES.map((p) => [p.id, p]));
export const profileById = (id: string | null | undefined) => (id ? byId.get(id) : undefined);

/** Allgemeines Profil zum Material, wenn eine Spule keins hat (PLA → Generic PLA) */
export function genericProfile(material: string): FilamentProfile | undefined {
  const m = material.toUpperCase().trim();
  return PROFILES.find((p) => p.vendor === "Generic" && p.name.toUpperCase() === `GENERIC ${m}`) ?? PROFILES.find((p) => p.vendor === "Generic" && p.type === m.split(/[\s+]/)[0]);
}

// Ohne gewähltes Profil: passendes Bambu-Lab-Profil aus Material und Sorte (Bambu-Drucker laufen damit am besten, auch mit
// Fremdfilament), erst danach Generic. Reihenfolge zählt: spezielle Sorten vor dem Grundmaterial.
const AUTO: [RegExp, string][] = [
  [/PLA.*CF|CF.*PLA/, "GFA50"],
  [/PETG.*CF|CF.*PETG/, "GFG50"],
  [/ASA.*CF/, "GFB51"],
  [/PAHT|PA6?.*CF|NYLON.*CF/, "GFN03"],
  [/PET.*CF/, "GFT01"],
  [/ABS.*GF/, "GFB50"],
  [/PETG.*MAT/, "GFG03"],
  [/PETG.*(TRANSLU|TRANSPAR|CLEAR)/, "GFG01"],
  [/PETG/, "GFG02"],
  [/ASA/, "GFB01"],
  [/ABS/, "GFB00"],
  [/TPU|TPE/, "GFU00"],
  [/\bPC\b/, "GFC00"],
  [/PVA/, "GFS04"],
  [/SILK|SEIDE/, "GFA06"],
  [/MAT/, "GFA01"],
  [/MARBLE|MARMOR/, "GFA07"],
  [/WOOD|HOLZ/, "GFA16"],
  [/GLOW|LEUCHT/, "GFA12"],
  [/SPARKLE|GLITTER|GLITZER|GALAXY/, "GFA08"],
  [/METAL/, "GFA02"],
  [/TRANSLU|TRANSPAR/, "GFA17"],
  [/PLA/, "GFA00"],
];
export function autoProfile(material: string, name = ""): FilamentProfile | undefined {
  const m = material.toUpperCase();
  const s = `${m} ${name.toUpperCase()}`;
  // Nur das Grundmaterial entscheidet, ob ein Stichwort der Sorte zählt (Matte-PETG ≠ Matte-PLA)
  const hit = AUTO.find(([re, id]) => re.test(s) && profileById(id)!.type.split("-")[0] === (m.split(/[\s+-]/)[0] || "PLA").replace(/^PA6?$/, "PA"));
  return (hit && profileById(hit[1])) ?? genericProfile(material);
}
